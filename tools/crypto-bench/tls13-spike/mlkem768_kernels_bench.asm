; Correctness-gated ML-KEM-768 kernel benchmark for the original 8088.
;
; This image is an architecture spike, not product code.  It times the exact
; portable kernels that dominate FIPS 203 ML-KEM-768 decapsulation:
;
;   * Keccak-f[1600]
;   * one 256-coefficient forward NTT
;   * one 256-coefficient inverse NTT
;   * one 256-coefficient base multiplication
;
; KEMMIN executes the complete minimum kernel multiset for a conventional
; decapsulation, including CCA re-encryption and implicit rejection:
;
;   44 Keccak-f + 6 NTT + 5 invNTT + 15 polynomial base multiplications
;
; KEMCACHE uses a matrix generated by this same machine before TCP:
;
;   17 Keccak-f + 6 NTT + 5 invNTT + 15 polynomial base multiplications
;
; The 27-permutation difference is the nine deterministic A^T matrix
; polynomials times the minimum three SHAKE128 squeeze blocks.  It is a cache
; of public deterministic work, not external key provisioning.
;
; DONE is emitted only after all four kernels match independent fixed oracles.
; The companion Unicorn checker compares every output byte; this image also
; checks frozen full-output word sums before entering the timed section.

bits 16
cpu 8086
org 0x1000

state_bytes equ 200
poly_words equ 256
poly_bytes equ 512

core_header:
    jmp short start
    nop
    db 'SEEDCORE'
    db 1
    db 0
    dw core_header_end - core_header
    dw (image_end - core_header + 511) / 512
    dw (image_end - core_header + 511) / 512
    dw 0
    dw 0
core_header_end:

start:
    cli
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x3ff0
    sti
    cld
    mov ax, 0x0003
    int 0x10
    call serial_init

    ; Full-output checks happen before timing.  The host checker independently
    ; inspects every byte, while these sums make DONE a target-side gate.
    call init_keccak_zero
    call keccak_f1600
    mov si, keccak_state
    mov cx, state_bytes / 2
    call checksum_words
    cmp ax, 0x8637
    jne fail

    call init_ntt_input
    mov si, poly_a
    call ntt_poly
    mov si, poly_a
    mov cx, poly_words
    call checksum_words
    cmp ax, 0x8080
    jne fail

    mov si, poly_a
    call invntt_poly
    mov si, poly_a
    mov cx, poly_words
    call checksum_words
    cmp ax, 0x01d8
    jne fail

    call init_basemul_inputs
    call basemul_poly
    mov si, poly_r
    mov cx, poly_words
    call checksum_words
    cmp ax, 0xc638
    jne fail

    call init_mulcache_inputs
    call mulcache_vector3
    call dot_vector3_cached
    mov si, poly_r
    mov cx, poly_words
    call checksum_words
    cmp ax, 0x15b7
    jne fail

    mov si, tag_check
    mov ax, 1
    call emit_check

    ; Individual portable-kernel measurements.
    call init_keccak_zero
    mov si, tag_keccak
    mov cx, 1
    mov bp, keccak_f1600
    call run_op
    mov si, keccak_state
    mov cx, state_bytes / 2
    call emit_tail

    call init_ntt_input
    mov si, tag_ntt
    mov cx, 1
    mov bp, ntt_poly_a
    call run_op
    mov si, poly_a
    mov cx, poly_words
    call emit_tail

    ; ntt_poly_a left the expected NTT-domain input for invNTT.
    mov si, tag_invntt
    mov cx, 1
    mov bp, invntt_poly_a
    call run_op
    mov si, poly_a
    mov cx, poly_words
    call emit_tail

    call init_basemul_inputs
    mov si, tag_basemul
    mov cx, 1
    mov bp, basemul_poly
    call run_op
    mov si, poly_r
    mov cx, poly_words
    call emit_tail

    ; mlkem-native's multiplication-cache strategy: two dynamic-vector
    ; cache builds and five K=3 dot products for a full decapsulation.
    call init_mulcache_inputs
    mov si, tag_mulcache
    mov cx, 1
    mov bp, kem_mulcache_kernels
    call run_op
    mov si, poly_r
    mov cx, poly_words
    call emit_tail

    ; Research-only speculate/commit kernel split.  KPCAND times a synthetic
    ; dominant-kernel multiset associated with K-PKE.Decrypt + G; it does not
    ; decode a ciphertext or produce a candidate.  KVALID times the remaining
    ; Keccak/lattice multiset; it does not serialize/re-encrypt/compare/select
    ; or produce a standard shared secret.  Neither is FIPS decapsulation.
    call init_model_inputs
    mov si, tag_kpcand
    mov cx, 1
    mov bp, kem_candidate_kernels
    call run_op
    mov si, poly_r
    mov cx, poly_words
    call emit_tail

    call init_model_inputs
    mov si, tag_kvalid
    mov cx, 1
    mov bp, kem_validation_cached_kernels
    call run_op
    mov si, poly_r
    mov cx, poly_words
    call emit_tail

    ; Two exact dominant-kernel multisets.  The helpers reinitialize operands
    ; only once; all kernels have fixed control flow over valid 16-bit values.
    call init_model_inputs
    mov si, tag_kemmin
    mov cx, 1
    mov bp, kem_min_kernels
    call run_op
    mov si, keccak_state
    mov cx, state_bytes / 2
    call emit_tail

    call init_model_inputs
    mov si, tag_kemcache
    mov cx, 1
    mov bp, kem_cached_kernels
    call run_op
    mov si, keccak_state
    mov cx, state_bytes / 2
    call emit_tail

    mov si, tag_done
    call emit_str
    call emit_crlf
.hang:
    hlt
    jmp .hang

fail:
    mov si, tag_fail
    call emit_str
    call emit_crlf
    jmp start.hang

ntt_poly_a:
    mov si, poly_a
    jmp ntt_poly

invntt_poly_a:
    mov si, poly_a
    jmp invntt_poly

