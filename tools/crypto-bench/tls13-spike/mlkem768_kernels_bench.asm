kem_min_kernels:
    mov cx, 44
.keccak:
    push cx
    call keccak_f1600
    pop cx
    loop .keccak
    jmp short kem_lattice_kernels

kem_cached_kernels:
    mov cx, 17
.keccak:
    push cx
    call keccak_f1600
    pop cx
    loop .keccak

kem_lattice_kernels:
    ; Alternate five transform pairs so every invocation starts with values
    ; inside the reference bounds, then execute the sixth forward transform.
    mov cx, 5
.transform_pair:
    push cx
    mov si, poly_a
    call ntt_poly
    mov si, poly_a
    call invntt_poly
    pop cx
    loop .transform_pair
    mov si, poly_a
    call ntt_poly
    call kem_mulcache_kernels
    ret

; ---------------------------------------------------------------------------
; Keccak-f[1600], portable 16-bit lane implementation
; ---------------------------------------------------------------------------

; State is 25 little-endian 64-bit lanes in x+5*y order.
keccak_f1600:
    mov word [round_index], 0
.round:
    ; C[x] = A[x,0] xor ... xor A[x,4].
    mov si, keccak_state
    mov di, keccak_c
    mov cx, 5
.theta_column:
    push cx
    mov cx, 4
.theta_word:
    mov ax, [si]
    xor ax, [si + 40]
    xor ax, [si + 80]
    xor ax, [si + 120]
    xor ax, [si + 160]
    stosw
    add si, 2
    loop .theta_word
    pop cx
    loop .theta_column

    ; D[x] = C[x-1] xor ROTL1(C[x+1]).
    xor bx, bx
.theta_d:
    mov al, [theta_next + bx]
    xor ah, ah
    add ax, keccak_c
    mov si, ax
    mov di, lane_tmp
    mov cl, 1
    call rotl64_to
    mov al, [theta_prev + bx]
    xor ah, ah
    add ax, keccak_c
    mov si, ax
    mov di, keccak_d
    mov ax, bx
    mov cl, 3
    shl ax, cl
    add di, ax
    mov cx, 4
.theta_xor:
    mov ax, [si]
    xor ax, [lane_tmp + (4 - 4)]
    ; lane_tmp must advance without consuming an extra address register.
    push si
    mov si, lane_tmp
    mov dx, 4
    sub dx, cx
    shl dx, 1
    add si, dx
    xor ax, [si]
    pop si
    ; Undo the first fixed xor above; it only keeps the 8086 addressing form
    ; uniform and is cancelled for word zero as well.
    xor ax, [lane_tmp]
    stosw
    add si, 2
    loop .theta_xor
    inc bx
    cmp bx, 5
    jb .theta_d

    ; A[x,y] ^= D[x].
    xor bx, bx
.theta_apply_column:
    mov ax, bx
    mov cl, 3
    shl ax, cl
    mov si, keccak_d
    add si, ax
    mov di, keccak_state
    add di, ax
    mov dx, 5
.theta_apply_row:
    mov cx, 4
.theta_apply_word:
    lodsw
    xor [di], ax
    add di, 2
    loop .theta_apply_word
    sub si, 8
    add di, 32
    dec dx
    jnz .theta_apply_row
    inc bx
    cmp bx, 5
    jb .theta_apply_column

    ; Rho and Pi: B[y,2*x+3*y] = ROT(A[x,y], rho[x,y]).
    xor bx, bx
.rho_pi:
    mov ax, bx
    mov cl, 3
    shl ax, cl
    mov si, keccak_state
    add si, ax
    mov al, [pi_offsets + bx]
    xor ah, ah
    mov di, keccak_b
    add di, ax
    mov cl, [rho_offsets + bx]
    call rotl64_to
    inc bx
    cmp bx, 25
    jb .rho_pi

    ; Chi, one row and one 16-bit word at a time.
    mov bx, keccak_b
    mov bp, keccak_state
    mov dx, 5
.chi_row:
    xor si, si
.chi_word:
    mov ax, [bx + si + 8]
    not ax
    and ax, [bx + si + 16]
    xor ax, [bx + si]
    mov [bp + si], ax

    mov ax, [bx + si + 16]
    not ax
    and ax, [bx + si + 24]
    xor ax, [bx + si + 8]
    mov [bp + si + 8], ax

    mov ax, [bx + si + 24]
    not ax
    and ax, [bx + si + 32]
    xor ax, [bx + si + 16]
    mov [bp + si + 16], ax

    mov ax, [bx + si + 32]
    not ax
    and ax, [bx + si]
    xor ax, [bx + si + 24]
    mov [bp + si + 24], ax

    mov ax, [bx + si]
    not ax
    and ax, [bx + si + 8]
    xor ax, [bx + si + 32]
    mov [bp + si + 32], ax

    add si, 2
    cmp si, 8
    jb .chi_word
    add bx, 40
    add bp, 40
    dec dx
    jnz .chi_row

    ; Iota.
    mov bx, [round_index]
    mov ax, bx
    mov cl, 3
    shl ax, cl
    mov si, round_constants
    add si, ax
    mov ax, [si]
    xor [keccak_state], ax
    mov ax, [si + 2]
    xor [keccak_state + 2], ax
    mov ax, [si + 4]
    xor [keccak_state + 4], ax
    mov ax, [si + 6]
    xor [keccak_state + 6], ax

    inc word [round_index]
    cmp word [round_index], 24
    jb .round
    ret

; SI=source lane, DI=destination lane, CL=constant rotation 0..63.
; The implementation rotates by whole 16-bit words plus two variable shifts,
; avoiding a bit-at-a-time 64-bit loop.
rotl64_to:
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    mov bp, si
    mov al, cl
    mov ah, al
    and al, 15
    mov [rot_bits], al
    mov dl, 16
    sub dl, al
    mov [rot_inv_bits], dl
    mov al, ah
    shr al, 1
    and ax, 0x0018
    mov bx, rot_word_pairs
    add bx, ax
    cmp byte [rot_bits], 0
    je .whole_words
    mov word [rot_outputs], 4
.mixed:
    mov dl, [bx]
    xor dh, dh
    mov si, dx
    mov ax, [bp + si]
    mov cl, [rot_bits]
    shl ax, cl
    mov dl, [bx + 1]
    xor dh, dh
    mov si, dx
    mov dx, [bp + si]
    mov cl, [rot_inv_bits]
    shr dx, cl
    or ax, dx
    stosw
    add bx, 2
    dec word [rot_outputs]
    jnz .mixed
    jmp short .done
.whole_words:
    mov cx, 4
.whole:
    mov dl, [bx]
    xor dh, dh
    mov si, dx
    mov ax, [bp + si]
    stosw
    add bx, 2
    loop .whole
.done:
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    ret

; ---------------------------------------------------------------------------
; ML-KEM q=3329 NTT kernels
; ---------------------------------------------------------------------------

; AX=a, BX=b -> AX = a*b*R^-1 mod q, signed reference representative.
fqmul:
    imul bx
    mov [fq_product_lo], ax
    mov [fq_product_hi], dx
    mov bx, -3327
    imul bx
    mov bx, ax
    mov ax, 3329
    imul bx
    sub [fq_product_lo], ax
    sbb [fq_product_hi], dx
    mov ax, [fq_product_hi]
    ret

; AX=signed value -> AX=centered Barrett representative.
barrett_reduce:
    mov [barrett_input], ax
    mov bx, 20159
    imul bx
    add dx, 0x0200
    mov ax, dx
    mov cl, 10
    sar ax, cl
    mov bx, 3329
    imul bx
    mov bx, ax
    mov ax, [barrett_input]
    sub ax, bx
    ret

; SI points to 256 signed coefficients.
ntt_poly:
    mov [poly_ptr], si
    mov word [ntt_k], 1
    mov word [ntt_len], 128
.layer:
    mov word [ntt_start], 0
.block:
    mov ax, [ntt_k]
    inc word [ntt_k]
    shl ax, 1
    mov bx, zetas
    add bx, ax
    mov ax, [bx]
    mov [ntt_zeta], ax

    mov ax, [ntt_start]
    shl ax, 1
    add ax, [poly_ptr]
    mov di, ax
    mov ax, [ntt_len]
    shl ax, 1
    mov [ntt_distance], ax
    add ax, di
    mov [ntt_end_ptr], ax
.butterfly:
    mov bp, di
    add bp, [ntt_distance]
    mov ax, [bp]
    mov bx, [ntt_zeta]
    call fqmul
    mov cx, ax
    mov dx, [di]
    mov ax, dx
    sub ax, cx
    mov [bp], ax
    add dx, cx
    mov [di], dx
    add di, 2
    cmp di, [ntt_end_ptr]
    jb .butterfly

    mov ax, [ntt_start]
    mov dx, [ntt_len]
    shl dx, 1
    add ax, dx
    mov [ntt_start], ax
    cmp ax, 256
    jb .block
    shr word [ntt_len], 1
    cmp word [ntt_len], 2
    jae .layer
    ret

; SI points to a polynomial in bit-reversed NTT order.
invntt_poly:
    mov [poly_ptr], si
    mov word [ntt_k], 127
    mov word [ntt_len], 2
.layer:
    mov word [ntt_start], 0
.block:
    mov ax, [ntt_k]
    dec word [ntt_k]
    shl ax, 1
    mov bx, zetas
    add bx, ax
    mov ax, [bx]
    mov [ntt_zeta], ax

    mov ax, [ntt_start]
    shl ax, 1
    add ax, [poly_ptr]
    mov di, ax
    mov ax, [ntt_len]
    shl ax, 1
    mov [ntt_distance], ax
    add ax, di
    mov [ntt_end_ptr], ax
.butterfly:
    mov bp, di
    add bp, [ntt_distance]
    mov dx, [di]
    mov ax, dx
    add ax, [bp]
    push dx
    call barrett_reduce
    pop dx
    mov [di], ax
    mov ax, [bp]
    sub ax, dx
    mov bx, [ntt_zeta]
    call fqmul
    mov [bp], ax
    add di, 2
    cmp di, [ntt_end_ptr]
    jb .butterfly

    mov ax, [ntt_start]
    mov dx, [ntt_len]
    shl dx, 1
    add ax, dx
    mov [ntt_start], ax
    cmp ax, 256
    jb .block
    shl word [ntt_len], 1
    cmp word [ntt_len], 128
    jbe .layer

    mov di, [poly_ptr]
    mov cx, poly_words
.scale:
    mov ax, [di]
    mov bx, 1441
    call fqmul
    stosw
    loop .scale
    ret

; One complete 256-coefficient polynomial base multiplication.
basemul_poly:
    mov word [bm_group], 0
.group:
    mov ax, [bm_group]
    mov bx, ax
    mov cl, 3
    shl ax, cl
    mov si, poly_a
    add si, ax
    mov di, poly_b
    add di, ax
    mov bp, poly_r
    add bp, ax

    mov ax, bx
    add ax, 64
    shl ax, 1
    mov bx, zetas
    add bx, ax
    mov ax, [bx]
    mov [bm_zeta], ax
    call basemul_pair

    add si, 4
    add di, 4
    add bp, 4
    neg word [bm_zeta]
    call basemul_pair

    inc word [bm_group]
    cmp word [bm_group], 64
    jb .group
    ret

; SI=a[2], DI=b[2], BP=r[2], bm_zeta fixed.
basemul_pair:
    mov [bm_a_ptr], si
    mov [bm_b_ptr], di
    mov [bm_r_ptr], bp

    mov ax, [si + 2]
    mov bx, [di + 2]
    call fqmul
    mov bx, [bm_zeta]
    call fqmul
    mov [bm_temp], ax
    mov si, [bm_a_ptr]
    mov di, [bm_b_ptr]
    mov ax, [si]
    mov bx, [di]
    call fqmul
    add ax, [bm_temp]
    mov bp, [bm_r_ptr]
    mov [bp], ax

    mov si, [bm_a_ptr]
    mov di, [bm_b_ptr]
    mov ax, [si]
    mov bx, [di + 2]
    call fqmul
    mov [bm_temp], ax
    mov ax, [si + 2]
    mov bx, [di]
    call fqmul
    add ax, [bm_temp]
    mov bp, [bm_r_ptr]
    mov [bp + 2], ax
    ret

; ---------------------------------------------------------------------------
; ML-KEM-native multiplication cache / K=3 dot-product strategy
; ---------------------------------------------------------------------------

; Build the 128-word odd-coefficient cache for each dynamic polynomial.
mulcache_vector3:
    mov si, poly_b
    mov di, mulcache_0
    call mulcache_poly
    mov si, poly_b1
    mov di, mulcache_1
    call mulcache_poly
    mov si, poly_b2
    mov di, mulcache_2
    jmp mulcache_poly

; SI=dynamic polynomial, DI=128-word output cache.
mulcache_poly:
    mov [cache_poly_ptr], si
    mov [cache_out_ptr], di
    mov word [cache_group], 0
.group:
    mov ax, [cache_group]
    mov bx, ax
    mov cl, 3
    shl ax, cl
    add ax, [cache_poly_ptr]
    mov si, ax
    mov ax, bx
    add ax, 64
    shl ax, 1
    mov bx, zetas
    add bx, ax
    mov ax, [bx]
    mov [cache_zeta], ax

    mov ax, [si + 2]
    mov bx, [cache_zeta]
    call fqmul
    mov di, [cache_out_ptr]
    stosw
    mov [cache_out_ptr], di

    mov ax, [si + 6]
    mov bx, [cache_zeta]
    neg bx
    call fqmul
    mov di, [cache_out_ptr]
    stosw
    mov [cache_out_ptr], di

    inc word [cache_group]
    cmp word [cache_group], 64
    jb .group
    ret

; Add one component's four signed 16x16 products into two 32-bit sums.
%macro DOT_COMPONENT 3
    mov ax, [%1 + bx + 2]
    imul word [%3 + si]
    add [dot_t0_lo], ax
    adc [dot_t0_hi], dx
    mov ax, [%1 + bx]
    imul word [%2 + bx]
    add [dot_t0_lo], ax
    adc [dot_t0_hi], dx
    mov ax, [%1 + bx]
    imul word [%2 + bx + 2]
    add [dot_t1_lo], ax
    adc [dot_t1_hi], dx
    mov ax, [%1 + bx + 2]
    imul word [%2 + bx]
    add [dot_t1_lo], ax
    adc [dot_t1_hi], dx
%endmacro

; One K=3 polynomial-vector dot product using the prebuilt dynamic cache.
dot_vector3_cached:
    xor bx, bx                         ; coefficient byte offset: 0,4,...508
    xor si, si                         ; cache byte offset:       0,2,...254
    mov bp, poly_r
    mov cx, 128
.pair:
    mov word [dot_t0_lo], 0
    mov word [dot_t0_hi], 0
    mov word [dot_t1_lo], 0
    mov word [dot_t1_hi], 0
    DOT_COMPONENT poly_a,  poly_b,  mulcache_0
    DOT_COMPONENT poly_a1, poly_b1, mulcache_1
    DOT_COMPONENT poly_a2, poly_b2, mulcache_2

    push bx
    mov ax, [dot_t0_lo]
    mov dx, [dot_t0_hi]
    call montgomery_reduce32
    mov [bp], ax
    mov ax, [dot_t1_lo]
    mov dx, [dot_t1_hi]
    call montgomery_reduce32
    mov [bp + 2], ax
    pop bx

    add bx, 4
    add si, 2
    add bp, 4
    dec cx
    jz .done
    jmp .pair
.done:
    ret

; DX:AX=signed 32-bit product/sum -> AX=Montgomery-reduced coefficient.
montgomery_reduce32:
    mov [fq_product_lo], ax
    mov [fq_product_hi], dx
    mov bx, -3327
    imul bx
    mov bx, ax
    mov ax, 3329
    imul bx
    sub [fq_product_lo], ax
    sbb [fq_product_hi], dx
    mov ax, [fq_product_hi]
    ret

; Exact mlkem-native pointwise work for one ML-KEM-768 decapsulation:
; cache b, cache sp, and compute decrypt + three matrix rows + public-key dot.
kem_mulcache_kernels:
    call mulcache_vector3
    call mulcache_vector3
    mov cx, 5
.dot:
    push cx
    call dot_vector3_cached
    pop cx
    loop .dot
    ret

; Synthetic proxy for the non-standard provisional path:
;   K-PKE.Decrypt: 3 NTT + one dynamic K=3 cache + one K=3 dot + one invNTT
;   G(m' || H(ek)): one Keccak-f[1600]
; H(ek) is already part of the locally generated ML-KEM secret key.
kem_candidate_kernels:
    call keccak_f1600
    mov si, poly_b
    call ntt_poly
    mov si, poly_b1
    call ntt_poly
    mov si, poly_b2
    call ntt_poly
    call mulcache_vector3
    call dot_vector3_cached
    mov si, poly_r
    jmp invntt_poly

; Synthetic proxy for remaining cached-matrix kernels after client Finished:
;   K-PKE.Encrypt: 7 PRF Keccaks + 3 NTT + one cache + four K=3 dots/invNTTs
;   implicit rejection J(z || c): 9 Keccaks
; The constant-time serialized ciphertext compare and selection are mandatory
; but are byte-work outside this dominant-kernel image.
kem_validation_cached_kernels:
    mov cx, 16
.keccak:
    push cx
    call keccak_f1600
    pop cx
    loop .keccak
    mov si, poly_b
    call ntt_poly
    mov si, poly_b1
    call ntt_poly
    mov si, poly_b2
    call ntt_poly
    call mulcache_vector3
    mov cx, 4
.dot_inv:
    push cx
    call dot_vector3_cached
    mov si, poly_r
    call invntt_poly
    pop cx
    loop .dot_inv
    ret

; ---------------------------------------------------------------------------
; Deterministic inputs
; ---------------------------------------------------------------------------

init_keccak_zero:
    mov di, keccak_state
    xor ax, ax
    mov cx, state_bytes / 2
    rep stosw
    ret

init_ntt_input:
