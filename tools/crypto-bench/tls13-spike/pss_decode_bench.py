#!/usr/bin/env python3
"""Correctness, size, and cycle-model gate for the 8086 RSA-PSS decoder.

This drives ``pss_decode.inc`` against the deterministic TLS 1.3
CertificateVerify generated by ``tls13_spike.py``.  RSA modular exponentiation
is deliberately outside this bench: its output (the 256-byte encoded message)
is the decoder input, matching the proposed split between the high RSA module
and resident TLS code.

86Box timing is authoritative; use ``run_pss_286.py`` for the 6 MHz 286
measurement.  The cycle figure here uses the existing calibrated 8088 model
only as a cheap regression signal.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from dataclasses import dataclass
from pathlib import Path


HERE = Path(__file__).resolve().parent
CRYPTO_BENCH = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(CRYPTO_BENCH))

import bench_harness as harness  # type: ignore
import tls13_spike as spike  # type: ignore


EM_ADDR = 0x7000
MESSAGE_HASH_ADDR = 0x7100
RESULT_ADDR = 0x7120
# Product-layout candidate: 0x7800..0x78ff can hold the CertificateVerify
# signature, leaving 0x7900..0x79ff for this 74-byte decoder scratch.
PSS_SCRATCH_ADDR = 0x7900
METRICS_MAGIC = 0x31535350  # ASCII "PSS1" as a little-endian dword.


@dataclass(frozen=True)
class PSSMaterial:
    signed_content: bytes
    message_hash: bytes
    encoded_message: bytes


def material() -> PSSMaterial:
    """Recover the exact EMSA-PSS encoded message from the frozen TLS vector."""
    vector = spike.build_vector()
    transcript = (
        vector.client_hello
        + vector.server_hello
        + vector.encrypted_extensions
        + vector.certificate
    )
    signed_content = spike.certificate_verify_input(transcript)
    message_hash = hashlib.sha256(signed_content).digest()
    modulus, exponent, _, _ = spike.rsa_fixture()
    if modulus.bit_length() != 2048 or exponent != 65537:
        raise RuntimeError("TLS spike RSA fixture is no longer RSA-2048/e=65537")
    signature_value = int.from_bytes(vector.certificate_verify_signature, "big")
    encoded_message = pow(signature_value, exponent, modulus).to_bytes(256, "big")
    oracle_encoded = spike.emsa_pss_encode(
        signed_content, spike.PSS_SALT, modulus.bit_length() - 1
    )
    if encoded_message != oracle_encoded:
        raise RuntimeError("RSA recovery and EMSA-PSS oracle disagree")
    return PSSMaterial(signed_content, message_hash, encoded_message)


def _body() -> str:
    return f"""
%define pss_scratch_base 0x{PSS_SCRATCH_ADDR:04x}
%include "tls13-spike/pss_decode.inc"
__pss_metrics:
    dd 0x{METRICS_MAGIC:08x}
    dw pss_verify_sha256_2048_salt32_end - pss_verify_sha256_2048_salt32_start
    dw pss_scratch_len
%include "core/sha256.inc"
"""


def _caller(call_count: int = 1) -> str:
    calls = []
    for _ in range(call_count):
        calls.extend(
            (
                f"    mov si, 0x{EM_ADDR:04x}",
                f"    mov di, 0x{MESSAGE_HASH_ADDR:04x}",
                "    call pss_verify_sha256_2048_salt32",
                "    jc __pss_rejected",
            )
        )
    return "\n".join(
        (
            f"    mov byte [0x{RESULT_ADDR:04x}], 0",
            *calls,
            f"    mov byte [0x{RESULT_ADDR:04x}], 1",
            "    jmp short __pss_return",
            "__pss_rejected:",
            f"    mov byte [0x{RESULT_ADDR:04x}], 0",
            "__pss_return:",
        )
    )


def build_runner(call_count: int = 1) -> tuple[harness.Run, int, int]:
    image, exports = harness.build(_body(), _caller(call_count))
    marker = struct.pack("<I", METRICS_MAGIC)
    offset = image.find(marker)
    if offset < 0:
        raise RuntimeError("PSS metrics marker missing from assembled image")
    code_bytes, scratch_bytes = struct.unpack_from("<HH", image, offset + 4)
    return harness.Run(image, exports), code_bytes, scratch_bytes


def run_case(
    runner: harness.Run,
    encoded_message: bytes,
    message_hash: bytes,
    *,
    cycles: bool = False,
) -> tuple[bool, int, int]:
    if len(encoded_message) != 256 or len(message_hash) != 32:
        raise ValueError("bad PSS test input shape")

    def setup(uc, _exports) -> None:
        uc.mem_write(EM_ADDR, encoded_message)
        uc.mem_write(MESSAGE_HASH_ADDR, message_hash)
        uc.mem_write(RESULT_ADDR, b"\xff")

    uc = runner.run(setup=setup, cycles=cycles)
    accepted = bytes(uc.mem_read(RESULT_ADDR, 1)) == b"\x01"
    return accepted, runner.instr_count, getattr(runner, "cycles", 0)


def _flip(value: bytes, index: int, mask: int = 1) -> bytes:
    changed = bytearray(value)
    changed[index] ^= mask
    return bytes(changed)


def run_gate() -> dict[str, object]:
    vector = material()
    runner, code_bytes, scratch_bytes = build_runner()
    cases = (
        ("valid recovered EM", vector.encoded_message, vector.message_hash, True),
        (
            "wrong CertificateVerify digest",
            vector.encoded_message,
            _flip(vector.message_hash, 0),
            False,
        ),
        (
            "maskedDB unused high bit set",
            bytes([vector.encoded_message[0] | 0x80])
            + vector.encoded_message[1:],
            vector.message_hash,
            False,
        ),
        (
            "maskedDB padding tamper",
            _flip(vector.encoded_message, 50),
            vector.message_hash,
            False,
        ),
        (
            "PSS H tamper",
            _flip(vector.encoded_message, 223),
            vector.message_hash,
            False,
        ),
        (
            "PSS trailer tamper",
            _flip(vector.encoded_message, 255),
            vector.message_hash,
            False,
        ),
    )
    case_results: list[dict[str, object]] = []
    for name, encoded_message, message_hash, expected in cases:
        accepted, instructions, _ = run_case(runner, encoded_message, message_hash)
        case_results.append(
            {
                "name": name,
                "accepted": accepted,
                "expected": expected,
                "passed": accepted is expected,
                "instructions": instructions,
            }
        )

    # Two-minus-one removes image startup/result overhead.  A few ABI setup
    # instructions remain in the delta; that makes this a conservative cheap
    # model and keeps the 86Box result the timing authority.
    one_runner, _, _ = build_runner(1)
    two_runner, _, _ = build_runner(2)
    _, one_instr, one_cycles = run_case(
        one_runner, vector.encoded_message, vector.message_hash, cycles=True
    )
    _, two_instr, two_cycles = run_case(
        two_runner, vector.encoded_message, vector.message_hash, cycles=True
    )
    report: dict[str, object] = {
        "profile": "EMSA-PSS SHA-256 / RSA-2048 / saltLen=32",
        "assembly_code_bytes": code_bytes,
        "transient_scratch_bytes": scratch_bytes,
        "recovered_em_bytes": len(vector.encoded_message),
        "certificate_verify_signed_content_bytes": len(vector.signed_content),
        "mgf1_sha256_blocks": 7,
        "pss_h_prime_sha256_blocks": 2,
        "certificate_verify_prehash_sha256_blocks": 3,
        "decoder_sha256_blocks": 9,
        "full_certificate_verify_post_rsa_sha256_blocks": 12,
        "decoder_instruction_count_delta": two_instr - one_instr,
        "decoder_8088_model_cycles_delta": two_cycles - one_cycles,
        "encoded_message_sha256": hashlib.sha256(vector.encoded_message).hexdigest(),
        "message_hash": vector.message_hash.hex(),
        "cases": case_results,
        "passed": all(bool(case["passed"]) for case in case_results),
    }
    return report


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    report = run_gate()
    if args.json:
        print(json.dumps(report, indent=2, sort_keys=True))
    else:
        print("TLS 1.3 RSA-PSS assembly decoder spike")
        for case in report["cases"]:
            assert isinstance(case, dict)
            verdict = "PASS" if case["passed"] else "FAIL"
            print(
                f"  [{verdict}] {case['name']}: "
                f"accepted={case['accepted']} expected={case['expected']}"
            )
        print(
            f"  code={report['assembly_code_bytes']} B  "
            f"scratch={report['transient_scratch_bytes']} B  "
            f"SHA blocks={report['decoder_sha256_blocks']} decoder / "
            f"{report['full_certificate_verify_post_rsa_sha256_blocks']} "
            "including signed-content hash"
        )
        print(
            "  8088-model decoder delta="
            f"{report['decoder_8088_model_cycles_delta']:,} cycles, "
            f"{report['decoder_instruction_count_delta']:,} instructions "
            "(ranking signal; 86Box 286 is authoritative)"
        )
    if not report["passed"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
