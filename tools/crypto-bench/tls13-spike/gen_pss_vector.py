#!/usr/bin/env python3
"""Regenerate the deterministic NASM vector used by the 286 PSS bench."""

from __future__ import annotations

import hashlib
from pathlib import Path

import pss_decode_bench


HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "pss_vector.inc"


def emit_bytes(label: str, value: bytes) -> list[str]:
    lines = [f"{label}:"]
    for offset in range(0, len(value), 16):
        chunk = value[offset : offset + 16]
        lines.append("    db " + ", ".join(f"0x{byte:02x}" for byte in chunk))
    lines.append(f"{label}_len equ $ - {label}")
    return lines


def main() -> None:
    vector = pss_decode_bench.material()
    lines = [
        "; Generated by gen_pss_vector.py. Test-only deterministic TLS 1.3 vector.",
        f"; signed-content SHA-256: {vector.message_hash.hex()}",
        "; recovered-EM SHA-256: "
        + hashlib.sha256(vector.encoded_message).hexdigest(),
        "",
    ]
    lines.extend(emit_bytes("pss_vector_signed_content", vector.signed_content))
    lines.append("")
    lines.extend(emit_bytes("pss_vector_encoded_message", vector.encoded_message))
    lines.append("")
    lines.extend(emit_bytes("pss_vector_message_hash", vector.message_hash))
    lines.extend(
        (
            "",
            "%if pss_vector_signed_content_len != 130",
            '%error "unexpected TLS 1.3 CertificateVerify signed-content size"',
            "%endif",
            "%if pss_vector_encoded_message_len != 256",
            '%error "unexpected EMSA-PSS encoded-message size"',
            "%endif",
            "%if pss_vector_message_hash_len != 32",
            '%error "unexpected CertificateVerify message-hash size"',
            "%endif",
            "",
        )
    )
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
