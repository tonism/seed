#!/usr/bin/env python3
"""Build the base-independent three-sector TLS 1.3 286 bootstrap boundary."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[3]
TARGET_BOOT = ROOT / "targets" / "ibm_pc_5150" / "boot"
SOURCE = TARGET_BOOT / "tls13" / "tls13_286_bootstrap.asm"
SOURCE_ABI = TARGET_BOOT / "tls13" / "tls13_286_abi.inc"
DEFAULT_BUILD = ROOT / "build" / "ibm_pc_5150"
DEFAULT_BOOTSTRAP = DEFAULT_BUILD / "tls13-286-bootstrap.bin"
DEFAULT_ABI = DEFAULT_BUILD / "tls13-286-product-abi.inc"
DEFAULT_LISTING = DEFAULT_BUILD / "tls13-286-bootstrap.lst"
DEFAULT_REPORT = DEFAULT_BUILD / "tls13-286-bootstrap.json"

BOOTSTRAP_BYTES = 3 * 512
ROOT_PHASE_KEY = 0x0329
ROOT_DESTINATION = 0x0700
ROOT_ENTRY = 0x0700
RESTORE_POINTER = 0x0702
WIPE_POINTER = 0x0704
ABORT_POINTER = 0x0706
CONVENTIONAL_RESERVE = 0x13A10


def atomic_write(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def build(bootstrap_out: Path, abi_out: Path, listing_out: Path, report_out: Path) -> None:
    bootstrap_out.parent.mkdir(parents=True, exist_ok=True)
    listing_out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix="tls13-286-bootstrap-", dir=bootstrap_out.parent
    ) as temporary:
        temporary_path = Path(temporary)
        image_path = temporary_path / "bootstrap.bin"
        listing_path = temporary_path / "bootstrap.lst"
        subprocess.run(
            [
                "nasm",
                "-I",
                f"{TARGET_BOOT}/",
                "-f",
                "bin",
                "-l",
                str(listing_path),
                "-o",
                str(image_path),
                str(SOURCE),
            ],
            check=True,
            cwd=ROOT,
        )
        image = image_path.read_bytes()
        listing = listing_path.read_bytes()

    if len(image) != BOOTSTRAP_BYTES:
        raise ValueError(
            f"286 bootstrap is {len(image)} bytes, expected exactly {BOOTSTRAP_BYTES}"
        )
    if image[0] != 0xEB:
        raise ValueError("286 bootstrap no longer begins with its short entry jump")
    if image[8:16] != b"S286BT02":
        raise ValueError("286 bootstrap header magic or fixed pointer table drifted")
    restore = int.from_bytes(image[2:4], "little")
    wipe = int.from_bytes(image[4:6], "little")
    abort = int.from_bytes(image[6:8], "little")
    for name, value in (
        ("restore", restore),
        ("wipe", wipe),
        ("abort", abort),
    ):
        if not ROOT_DESTINATION <= value < ROOT_DESTINATION + BOOTSTRAP_BYTES:
            raise ValueError(f"286 bootstrap {name} pointer escaped the image: {value:#06x}")

    parent_match = re.search(
        rb"^\s*\d+\s+([0-9A-Fa-f]{8})\s+"
        rb"[0-9A-Fa-f<>]+\s+bootstrap_config_crc\s+dw\b",
        listing,
        re.MULTILINE,
    )
    if parent_match is None:
        raise ValueError("286 bootstrap parent-SP storage symbol is absent")
    parent_sp = ROOT_DESTINATION + int(parent_match.group(1), 16)
    if not ROOT_DESTINATION <= parent_sp <= ROOT_DESTINATION + BOOTSTRAP_BYTES - 2:
        raise ValueError("286 bootstrap parent-SP storage escaped its image")

    digest = hashlib.sha256(image).hexdigest()
    abi = f"""; Generated by {SOURCE.relative_to(ROOT)}.
; Base-independent: safe as a prerequisite of both pack-base and final links.
%define TLS13_286_PRODUCT_ROOT_PHASE_KEY 0x{ROOT_PHASE_KEY:04x}
%define TLS13_286_PRODUCT_ROOT_DESTINATION 0x{ROOT_DESTINATION:04x}
%define TLS13_286_PRODUCT_ROOT_ENTRY 0x{ROOT_ENTRY:04x}
%define TLS13_286_PRODUCT_BOOTSTRAP_SECTORS 3
%define TLS13_286_PRODUCT_BOOTSTRAP_RESTORE_PTR 0x{RESTORE_POINTER:04x}
%define TLS13_286_PRODUCT_BOOTSTRAP_WIPE_PTR 0x{WIPE_POINTER:04x}
%define TLS13_286_PRODUCT_BOOTSTRAP_ABORT_PTR 0x{ABORT_POINTER:04x}
%define TLS13_286_PRODUCT_BOOTSTRAP_PARENT_SP 0x{parent_sp:04x}
%define TLS13_286_PRODUCT_CONVENTIONAL_RESERVE 0x{CONVENTIONAL_RESERVE:04x}
"""
    report = {
        "schema": "seed-tls13-286-bootstrap-v1",
        "source": str(SOURCE.relative_to(ROOT)),
        "source_abi": str(SOURCE_ABI.relative_to(ROOT)),
        "bootstrap": {
            "bytes": len(image),
            "sectors": BOOTSTRAP_BYTES // 512,
            "sha256": digest,
            "phase_key": f"0x{ROOT_PHASE_KEY:04x}",
            "destination": f"0x{ROOT_DESTINATION:04x}",
            "entry": f"0x{ROOT_ENTRY:04x}",
            "restore_pointer": f"0x{restore:04x}",
            "wipe_pointer": f"0x{wipe:04x}",
            "abort_pointer": f"0x{abort:04x}",
            "parent_sp_storage": f"0x{parent_sp:04x}",
        },
        "conventional_reserve_bytes": CONVENTIONAL_RESERVE,
        "tail_discovery": {
            "source": "resident core total-sector word and final-sector S286TL02 footer",
            "sector_width_bits": 16,
            "legacy_phase_key_required_for_tail": False,
        },
    }

    # Publish dependent metadata first.  The bootstrap binary is the Make
    # transaction marker and must become visible only after every side output.
    atomic_write(listing_out, listing)
    atomic_write(abi_out, abi.encode("ascii"))
    atomic_write(
        report_out,
        (json.dumps(report, indent=2, sort_keys=True) + "\n").encode("utf-8"),
    )
    atomic_write(bootstrap_out, image)
    print(json.dumps(report, indent=2, sort_keys=True))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bootstrap-out", type=Path, default=DEFAULT_BOOTSTRAP)
    parser.add_argument("--abi-out", type=Path, default=DEFAULT_ABI)
    parser.add_argument("--listing-out", type=Path, default=DEFAULT_LISTING)
    parser.add_argument("--report-out", type=Path, default=DEFAULT_REPORT)
    args = parser.parse_args()
    build(
        args.bootstrap_out,
        args.abi_out,
        args.listing_out,
        args.report_out,
    )


if __name__ == "__main__":
    main()
